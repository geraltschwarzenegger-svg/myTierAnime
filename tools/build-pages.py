#!/usr/bin/env python3
"""Build the GitHub Pages artifact from runtime files only; no third-party packages."""
from pathlib import Path
from datetime import datetime, timezone
import hashlib
import json
import os
import shutil
import subprocess

ROOT = Path(__file__).resolve().parent.parent
DEST = ROOT / '.pages-build'
MARKER = '.astrava-pages-build'
FILES = ('index.html', 'data.json', 'anime-tierlist-2026-10-11.json', 'SECURITY.md')
DIRECTORIES = ('assets', 'docs/images')


def build():
    if DEST.exists():
        if DEST.is_symlink() or not (DEST / MARKER).is_file():
            raise RuntimeError('Refusing to replace an unrecognised build directory')
        shutil.rmtree(DEST)
    DEST.mkdir()
    (DEST / MARKER).write_text('Generated by tools/build-pages.py\n')
    for name in FILES:
        shutil.copy2(ROOT / name, DEST / name)
    for name in DIRECTORIES:
        if any(p.is_symlink() for p in (ROOT / name).rglob('*')):
            raise RuntimeError('Symbolic links are not supported in the Pages artifact')
        shutil.copytree(ROOT / name, DEST / name)
    (DEST / '.nojekyll').touch()

    # Fail before upload if the collection, library or new album photos are missing.
    state = json.loads((DEST / 'data.json').read_text())['state']
    if (DEST / 'data.json').read_bytes() != (DEST / 'anime-tierlist-2026-10-11.json').read_bytes():
        raise RuntimeError('Collection snapshots disagree')
    for entry in json.loads((DEST / 'assets/covers/library.json').read_text())['items']:
        if not (DEST / entry['file']).is_file():
            raise RuntimeError('A local poster is missing')
    for entry in json.loads((DEST / 'assets/album/replacements.json').read_text())['items']:
        if not (DEST / entry['file']).is_file():
            raise RuntimeError('A replacement album image is missing')
    commit = os.environ.get('GITHUB_SHA') or subprocess.check_output(
        ['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip()
    contents = [p for p in DEST.rglob('*') if p.is_file()]
    info = {
        'app': 'ASTRAVA', 'version': '5.0.0', 'sourceCommit': commit,
        'builtAt': datetime.now(timezone.utc).isoformat(),
        'files': len(contents), 'runtimeBytes': sum(p.stat().st_size for p in contents),
        'animeCount': sum(len(t['items']) for t in state['tiers']),
        'collectionSha256': hashlib.sha256((DEST / 'data.json').read_bytes()).hexdigest(),
    }
    (DEST / 'build-info.json').write_text(json.dumps(info, ensure_ascii=False, indent=2) + '\n')
    print(json.dumps(info, ensure_ascii=False))


if __name__ == '__main__':
    build()
