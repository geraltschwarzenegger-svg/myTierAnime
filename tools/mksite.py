#!/usr/bin/env python3
"""Собрать index.html для GitHub Pages из src/app.html.

Офлайн-файл возит внутри 254 подмножества шрифтов и html2canvas — суммарно
10,8 МБ base64. Сайт использует собственные шрифты и html2canvas из assets/vendor.
Сборка добавляет SRI и CSP с хешами встроенных скриптов, копирует ассеты
и обновляет ту же политику для HTTP-заголовков Worker.

    python3 tools/mksite.py src/app.html index.html
"""
import re
import sys
import base64
import hashlib
import json
import shutil
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
VENDOR = REPO / 'assets/vendor'

# блок встроенных шрифтов начинается этим маркером и тянется до </style>,
# сразу за ним идёт <script src="<uuid>"> с html2canvas
FONT_BLOCK = re.compile(
    r'<style>/\* cyrillic-ext \*/.*?</style>\s*<script src="[0-9a-f-]{36}"></script>',
    re.S,
)

def replacement():
    integrity = 'sha384-' + base64.b64encode(hashlib.sha384((VENDOR / 'html2canvas-1.4.1.min.js').read_bytes()).digest()).decode()
    return '<link rel="stylesheet" href="assets/vendor/fonts.css">\n' + f'<script src="assets/vendor/html2canvas-1.4.1.min.js" integrity="{integrity}" defer></script>'

EXTRA_HEAD = """<meta name="description" content="myTierAnime — твоя коллекция аниме, тиры, календарь просмотров и альбом любимых героев.">
<meta name="theme-color" content="#0b1019">
<meta name="referrer" content="no-referrer">
<meta property="og:type" content="website">
<meta property="og:title" content="Аниме · Тир-лист">
<meta property="og:description" content="Личный канон: тиры S · A · B · C, обложки, даты просмотра.">
<link rel="icon" href="data:image/svg+xml,%3Csvg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 64 64'%3E%3Crect width='64' height='64' rx='14' fill='%23120e24'/%3E%3Ctext x='32' y='45' font-family='Georgia,serif' font-size='38' fill='%23ff5c95' text-anchor='middle'%3ES%3C/text%3E%3C/svg%3E">
"""


def build(app_path: str, out_path: str) -> None:
    src = open(app_path, encoding="utf-8").read()

    out, n = FONT_BLOCK.subn(lambda _: replacement(), src, count=1)
    if n != 1:
        raise SystemExit("не нашёл встроенный блок шрифтов — формат src/app.html изменился")

    out = re.sub(r'<link rel="preconnect"[^>]+>\s*', '', out)
    out = out.replace('\x00', r'\u0000')
    out = out.replace("<title>", EXTRA_HEAD + "<title>", 1)

    hashes = []
    for attrs, code in re.findall(r'<script\b([^>]*)>(.*?)</script>', out, re.S | re.I):
        if re.search(r'\bsrc\s*=|\btype\s*=\s*["\']application/json', attrs, re.I):
            continue
        hashes.append("'sha256-" + base64.b64encode(hashlib.sha256(code.encode()).digest()).decode() + "'")
    policy = "; ".join([
        "default-src 'self'", "script-src 'self' " + ' '.join(hashes),
        "style-src 'self' 'unsafe-inline'", "img-src 'self' https: data: blob:",
        "font-src 'self' data:", "connect-src 'self' https://api.github.com",
        "object-src 'none'", "base-uri 'none'", "form-action 'self'", "frame-src 'self'"
    ])
    meta = '<meta http-equiv="Content-Security-Policy" content="' + policy + '">\n'
    out = out.replace('<meta charset="UTF-8">', '<meta charset="UTF-8">\n' + meta, 1)
    (REPO / 'site/src/security-policy.mjs').write_text('// Generated by tools/mksite.py. Rebuild after editing inline scripts.\nexport const WEB_CSP = ' + json.dumps(policy) + ';\n')
    target = Path(out_path).resolve().parent / 'assets/vendor'
    if target != VENDOR:
        shutil.copytree(VENDOR, target, dirs_exist_ok=True)

    open(out_path, "w", encoding="utf-8").write(out)
    before, after = len(src.encode()), len(out.encode())
    print(f"{out_path}: {after/1024:.0f} КБ (исходник {before/1024:.0f} КБ)")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    build(sys.argv[1], sys.argv[2])
